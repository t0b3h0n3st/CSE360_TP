/**
 * <p> Title: LessonsLearned </p>
 *
 * <p> Description: Entity class that models a single "lesson learned" record. A lesson is
 * written by a contributor and consists of an author, a title, a body of text, and a
 * database-assigned ID. Two lock flags (title and description) allow a curator to prevent
 * the original author from editing the corresponding field.</p>
 *
 * <p> Instances of this class mirror one row of the {@code lessons} table in the database
 * (columns: id, author, title, text, isTitleLocked, isDescriptionLocked). This class does
 * not itself perform validation; see
 * {@link guiCreateLesson.ModelCreateLesson#validateTitle(String)} and
 * {@link guiCreateLesson.ModelCreateLesson#validateText(String)}.</p>
 *
 * @author Harrison
 * @version 2.0
 * @see LessonsLearnedCollection
 * @see database.Database
 */

/* 
 * DATABASE, store a LESSONS table:
 * 
 * [ author ] , [lessonTitle], [lessonTitle
 */
public class LessonsLearned {
	// instance fields per each OBJECT: 
	
	private String author;
	private String lessonTitle;
	private String lessonText; 
	private String curatorAdditionalInformation;
	private int lessonID; 
	private boolean isTitleLocked;
	private boolean isDescriptionLocked;
	
	/**
	 * Default constructor. It is private and intentionally unused so that a lesson cannot be
	 * created without at least an author, title, and text.
	 */
	
	private LessonsLearned() {
		
	}
	
	/**
	 * Creates a new lesson that has not yet been stored in the database. The ID is left at its
	 * default value ({@code 0}) because it is generated by the database when the lesson is
	 * inserted, and both lock flags default to {@code false}.
	 *
	 * @param author the username of the contributor who wrote the lesson
	 * @param lessonTitle the title of the lesson
	 * @param lessonText the body text of the lesson
	 */
	
	public LessonsLearned(String author, String lessonTitle, String lessonText) {
		this.author = author;
		this.lessonTitle = lessonTitle;
		this.lessonText = lessonText;
	}
	
	
	public LessonsLearned(String author, String lessonTitle, String lessonText,
	        int lessonID, String curatorAdditionalInformation) {

	    this.author = author;
	    this.lessonTitle = lessonTitle;
	    this.lessonText = lessonText;
	    this.lessonID = lessonID;
	    this.curatorAdditionalInformation = curatorAdditionalInformation;
	}
	
	/**
	 * Creates a lesson with every field specified. This is used when reading an existing
	 * lesson back from the database, where the ID and lock flags are already known.
	 *
	 * @param author the username of the contributor who wrote the lesson
	 * @param lessonTitle the title of the lesson
	 * @param lessonText the body text of the lesson
	 * @param lessonID the unique ID assigned to the lesson by the database
	 * @param isTitleLocked {@code true} if the title is locked against editing
	 * @param isDescriptionLocked {@code true} if the description is locked against editing
	 */
	
	public LessonsLearned(String author, String lessonTitle, String lessonText, int lessonID) {
		this.author = author;
		this.lessonTitle = lessonTitle;
		this.lessonText = lessonText;
		this.lessonID = lessonID;
	}
	
	// GETTERS:
	
	/** @return the username of the contributor who wrote this lesson */
	public String getAuthor() { return this.author; }
	
	/** @return the title of this lesson */
	public String getLessonTitle() { return this.lessonTitle; }
	
	/** @return the body text of this lesson */
	public String getLessonText() { return this.lessonText; }
	
	/** @return the additional information added by the curator */
	public String getCuratorAdditionalInformation() { return this.curatorAdditionalInformation; }
	
	/** @return the database-assigned ID of this lesson ({@code 0} if not yet stored) */
	public int getLessonID() { return this.lessonID; }
	
	/** @return {@code true} if the title is locked against editing, {@code false} otherwise */
	public boolean getIsTitleLocked() {return this.isTitleLocked;}
	
	/** @return {@code true} if the description is locked against editing, {@code false} otherwise */
	public boolean getIsDescriptionLocked() {return this.isDescriptionLocked;}
	
	
	// SETTERS:
	
	/** @param author the username of the contributor who wrote this lesson */
	public void setLessonTitle(String lessonTitle) { this.lessonTitle = lessonTitle; }
	
	/** @param lessonTitle the new title of this lesson */
	public void setLessonText(String lessonText) { this.lessonText = lessonText; }
	
	/** @param curatorAdditionalInformation additional information added by the curator */
	public void setCuratorAdditionalInformation(String curatorAdditionalInformation) { this.curatorAdditionalInformation = curatorAdditionalInformation; }
	
	/** @param lessonID the database-assigned ID of this lesson */
	public void setLessonID(int lessonID) { this.lessonID = lessonID; }
	
	/** @param isTitleLocked {@code true} to lock the title against editing */
	public void setIsTitleLocked(boolean isTitleLocked) {this.isTitleLocked = isTitleLocked; }
	
	/** @param isDescriptionLocked {@code true} to lock the description against editing */
	public void setIsDescriptionLocked(boolean isDescriptionLocked) {this.isDescriptionLocked = isDescriptionLocked;}
	
	// VALIDATION:
	
	// validateTitle
	
	// validateText
}
